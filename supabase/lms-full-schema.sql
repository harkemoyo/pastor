-- 1. Extend students table with pastor signup & transcript fields
alter table if exists public.students
  add column if not exists cohort text,
  add column if not exists church_size text,
  add column if not exists age integer,
  add column if not exists profile_picture text;

-- 2. Courses
create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  code text unique not null,
  title text not null,
  term text not null default 'AY2027-T1',
  description text,
  cover_image text default '/images/course-hermeneutics.svg',
  instructor_username text,
  instructor_name text,
  credits numeric(3,1) not null default 3.0,
  start_date date,
  end_date date,
  status text not null default 'current' check (status in ('current', 'past', 'upcoming', 'active', 'inactive', 'archived')),
  capacity integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists courses_status_idx on public.courses (status);
create index if not exists courses_instructor_idx on public.courses (instructor_username);

-- 3. Course Modules / Weekly Units
create table if not exists public.course_modules (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  sort_order integer not null default 1,
  title text not null,
  total_topics integer not null default 1,
  instructor_username text,
  unlock_date date,
  due_date date,
  created_at timestamptz not null default now()
);

create index if not exists course_modules_course_id_idx on public.course_modules (course_id);
create index if not exists course_modules_instructor_idx on public.course_modules (instructor_username);

-- 4. Custom Module Lessons, Assignments, Discussions & Quizzes/Exams
create table if not exists public.module_lessons (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  module_id bigint not null,
  topic_key text unique not null,
  sort_order integer not null default 1,
  title text not null,
  banner_title text,
  topic_type text not null default 'reading' check (topic_type in ('reading', 'assignment', 'journal', 'quiz', 'discussion', 'exam')),
  content_html text not null default '',
  scripture_ref text,
  quiz_questions jsonb default '[]'::jsonb,
  max_score numeric(5,2) not null default 100,
  pass_score numeric(5,2) not null default 60,
  max_attempts integer not null default 3,
  time_limit_minutes integer,
  due_date date,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists module_lessons_course_mod_idx on public.module_lessons (course_id, module_id);

-- 5. Course Enrolments
create table if not exists public.enrolments (
  id bigint generated by default as identity primary key,
  student_username text not null,
  student_id text,
  course_id bigint not null references public.courses(id) on delete cascade,
  status text not null default 'active' check (status in ('active', 'completed', 'dropped', 'removed')),
  enrolled_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (student_username, course_id)
);

create index if not exists enrolments_student_idx on public.enrolments (student_username);
create index if not exists enrolments_course_idx on public.enrolments (course_id);

-- 6. Student Topic Completion Progress
create table if not exists public.student_progress (
  student_username text not null,
  course_id bigint not null,
  completed_topics jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now(),
  primary key (student_username, course_id)
);

create index if not exists student_progress_course_idx on public.student_progress (course_id);

-- 7. Student Submissions (Written Assignments, Learning Journals, Quizzes, Exams)
create table if not exists public.submissions (
  id text primary key,
  student_username text not null,
  student_name text not null,
  course_id bigint not null,
  module_id bigint not null,
  topic_id text not null,
  topic_title text,
  submission_type text not null default 'assignment' check (submission_type in ('assignment', 'journal', 'quiz', 'exam')),
  content_text text,
  quiz_answers jsonb,
  score numeric(5,2),
  max_score numeric(5,2) not null default 100,
  grade_letter text,
  feedback text,
  graded_by text,
  graded_at timestamptz,
  attempt_number integer not null default 1,
  status text not null default 'submitted' check (status in ('submitted', 'graded')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists submissions_student_course_idx on public.submissions (student_username, course_id);
create index if not exists submissions_course_module_idx on public.submissions (course_id, module_id);
create index if not exists submissions_status_idx on public.submissions (status);

-- 8. Weekly Cohort Discussion Forum Posts & Replies
create table if not exists public.discussion_posts (
  id text primary key,
  course_id bigint not null,
  module_id bigint not null,
  parent_id text references public.discussion_posts(id) on delete cascade,
  author_username text not null,
  author_name text not null,
  author_role text not null default 'student',
  body text not null,
  grade_score numeric(5,2),
  grade_feedback text,
  graded_by text,
  created_at timestamptz not null default now()
);

create index if not exists discussion_posts_course_mod_idx on public.discussion_posts (course_id, module_id, created_at);
create index if not exists discussion_posts_parent_idx on public.discussion_posts (parent_id);

-- 9. Peer Reviews (UoPeople-style peer feedback on reflections)
create table if not exists public.peer_reviews (
  id text primary key,
  submission_id text not null references public.submissions(id) on delete cascade,
  course_id bigint not null,
  reviewer_username text not null,
  reviewer_name text not null,
  rating integer not null check (rating between 1 and 5),
  feedback text not null,
  created_at timestamptz not null default now(),
  unique (submission_id, reviewer_username)
);

create index if not exists peer_reviews_submission_idx on public.peer_reviews (submission_id);

-- 10. Course Announcements
create table if not exists public.course_announcements (
  id text primary key,
  course_id bigint not null,
  author_username text not null,
  author_name text not null,
  title text not null,
  body text not null,
  created_at timestamptz not null default now()
);

create index if not exists course_announcements_course_idx on public.course_announcements (course_id, created_at desc);

-- 11. Digital Library Materials
create table if not exists public.library_materials (
  id text primary key,
  title text not null,
  type text not null default 'link' check (type in ('pdf', 'book', 'video', 'audio', 'link')),
  url text not null,
  description text,
  course_id bigint,
  added_by text,
  added_by_name text,
  created_at timestamptz not null default now()
);

create index if not exists library_materials_course_idx on public.library_materials (course_id);

-- 12. Enable Row Level Security (RLS) on all tables
alter table public.courses enable row level security;
alter table public.course_modules enable row level security;
alter table public.module_lessons enable row level security;
alter table public.enrolments enable row level security;
alter table public.student_progress enable row level security;
alter table public.submissions enable row level security;
alter table public.discussion_posts enable row level security;
alter table public.peer_reviews enable row level security;
alter table public.course_announcements enable row level security;
alter table public.library_materials enable row level security;

-- Read policies for authenticated users on public catalog / course content
drop policy if exists "Authenticated read courses" on public.courses;
create policy "Authenticated read courses" on public.courses
  for select to authenticated using (true);

drop policy if exists "Authenticated read modules" on public.course_modules;
create policy "Authenticated read modules" on public.course_modules
  for select to authenticated using (true);

drop policy if exists "Authenticated read lessons" on public.module_lessons;
create policy "Authenticated read lessons" on public.module_lessons
  for select to authenticated using (true);

drop policy if exists "Authenticated read announcements" on public.course_announcements;
create policy "Authenticated read announcements" on public.course_announcements
  for select to authenticated using (true);

drop policy if exists "Authenticated read library" on public.library_materials;
create policy "Authenticated read library" on public.library_materials
  for select to authenticated using (true);

-- Discussion posts visible to authenticated cohort members
drop policy if exists "Authenticated read discussions" on public.discussion_posts;
create policy "Authenticated read discussions" on public.discussion_posts
  for select to authenticated using (true);

-- Admin / Super Admin management policies using cached (select auth.jwt())
drop policy if exists "Admins manage courses" on public.courses;
create policy "Admins manage courses" on public.courses
  for all to authenticated
  using ((select auth.jwt() ->> 'role') in ('admin', 'super_admin'))
  with check ((select auth.jwt() ->> 'role') in ('admin', 'super_admin'));

drop policy if exists "Admins manage submissions" on public.submissions;
create policy "Admins manage submissions" on public.submissions
  for all to authenticated
  using ((select auth.jwt() ->> 'role') in ('teacher', 'admin', 'super_admin'))
  with check ((select auth.jwt() ->> 'role') in ('teacher', 'admin', 'super_admin'));

